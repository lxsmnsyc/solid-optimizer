/**
 * The shape of `results.json`, the statistics behind it, and the Markdown
 * report written from it.
 */

export const VARIANTS = ['plain', 'optimized'] as const;

/** The apps in `src`, and how the report describes each. */
export const APPS = {
  demo: 'The app is the demo with every page rendered at once and none lazy (`src/demo/App.tsx`).',
  hackernews:
    "The app is Hacker News's two story lists and a story's comments, from its fixtures, without the router (`src/hackernews/App.tsx`).",
  tracker:
    "The app is the tracker's layout with its 40 issues read at once instead of loaded, and no issue selected (`src/tracker/App.tsx`).",
} as const;
export type App = keyof typeof APPS;

export function isApp(value: string): value is App {
  return Object.hasOwn(APPS, value);
}
export type Variant = (typeof VARIANTS)[number];

/** One measure of the two builds. */
export interface Row {
  label: string;
  plain: number;
  optimized: number;
}

export interface TimingRow extends Row {
  /** The larger median absolute deviation of the two sides. */
  noise: number;
  /** Whether the change is larger than 3 times the noise. */
  real: boolean;
  samples: Record<Variant, number[]>;
}

/** What `results.json` holds. The website reads it. */
export interface Results {
  /** Missing in results written before there was more than one app. */
  app?: App;
  date: string;
  node: string;
  cpu: string;
  browser: string;
  runs: number;
  warmup: number;
  client: Record<string, Row>;
  server: Record<string, Row>;
  hydration: Record<string, Row>;
  timings: Record<string, TimingRow>;
}

export type Samples = Partial<Record<string, Record<Variant, number[]>>>;

export const TIMINGS: Readonly<Record<string, string>> = {
  coldMount: 'First client render, fresh page (µs)',
  mount: 'Client render, warm (µs)',
  dispose: 'Dispose, warm (µs)',
  heap: 'Heap held by one mounted app (B)',
  hydrate: 'Hydration, fresh page (µs)',
  ssr: '`renderToString`, warm (µs)',
};

export function median(values: readonly number[]): number {
  const sorted = values.toSorted((a, b) => a - b);
  const middle = Math.floor(sorted.length / 2);
  if (sorted.length % 2 === 1) {
    return sorted[middle] ?? 0;
  }
  return ((sorted[middle - 1] ?? 0) + (sorted[middle] ?? 0)) / 2;
}

export function deviate(values: readonly number[]): number {
  const center = median(values);
  const deviations: number[] = [];
  for (const value of values) {
    deviations.push(Math.abs(value - center));
  }
  return median(deviations);
}

export function summarize(samples: Samples): Record<string, TimingRow> {
  const result: Record<string, TimingRow> = {};
  for (const [name, label] of Object.entries(TIMINGS)) {
    const entry = samples[name];
    if (entry) {
      const plain = median(entry.plain);
      const optimized = median(entry.optimized);
      const noise = Math.max(deviate(entry.plain), deviate(entry.optimized));
      const real = Math.abs(optimized - plain) > noise * 3;
      result[name] = { label, plain, optimized, noise, real, samples: entry };
    }
  }
  return result;
}

function formatNumber(value: number): string {
  return Number.isInteger(value) ? String(value) : value.toFixed(1);
}

function formatChange(before: number, after: number): string {
  if (before === after) {
    return '0';
  }
  const delta = after - before;
  const percent = before === 0 ? 0 : (delta / before) * 100;
  const sign = delta > 0 ? '+' : '−';
  return `${sign}${formatNumber(Math.abs(delta))} (${sign}${Math.abs(percent).toFixed(1)}%)`;
}

function writeCounts(rows: Record<string, Row>): string {
  const lines = ['| Count | Plain | Optimized | Change |', '| --- | --- | --- | --- |'];
  for (const entry of Object.values(rows)) {
    const plain = formatNumber(entry.plain);
    const optimized = formatNumber(entry.optimized);
    lines.push(
      `| ${entry.label} | ${plain} | ${optimized} | ${formatChange(entry.plain, entry.optimized)} |`,
    );
  }
  return lines.join('\n');
}

function writeTimings(rows: Record<string, TimingRow>): string {
  const lines = [
    '| Timing | Plain | Optimized | Change | Noise | Real |',
    '| --- | --- | --- | --- | --- | --- |',
  ];
  for (const entry of Object.values(rows)) {
    const plain = entry.plain.toFixed(1);
    const optimized = entry.optimized.toFixed(1);
    const delta = formatChange(entry.plain, entry.optimized);
    lines.push(
      `| ${entry.label} | ${plain} | ${optimized} | ${delta} | ±${entry.noise.toFixed(1)} | ${entry.real ? 'yes' : 'no'} |`,
    );
  }
  return lines.join('\n');
}

export function writeReport(results: Results): string {
  return `# Runtime benchmarks

Generated by \`pnpm --filter runtime-bench bench${results.app === undefined || results.app === 'demo' ? '' : ` --app ${results.app}`}\`.

${results.date}. Node ${results.node}, ${results.cpu}, Chromium ${results.browser} headless. Median of ${String(results.runs)} samples per timing, after ${String(results.warmup)} warmup samples.

${APPS[results.app ?? 'demo']} Each build is one minified chunk. Counts are exact. A timing change is real when it is larger than 3 times the noise, the larger median absolute deviation of the two sides.

## Client render

${writeCounts(results.client)}

## Server render

${writeCounts(results.server)}

## Hydration

${writeCounts(results.hydration)}

## Timings

${writeTimings(results.timings)}
`;
}
